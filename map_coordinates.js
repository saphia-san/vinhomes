function buildUnitCoordObj(code, item) {
    return {
        macan: code,
        x: item.x,
        y: item.y,
        name: "Căn " + code
    };
}

function getUnitMapCoordinates(macan) {
    if (!macan) return null;
    var raw = String(macan).trim().toUpperCase();
    var cleanCode = raw.replace(/\s+/g, '');
    var altCode = cleanCode.replace(/^Đ/, 'D');

    if (EXACT_UNIT_MAP_COORDINATES[raw]) return buildUnitCoordObj(raw, EXACT_UNIT_MAP_COORDINATES[raw]);
    if (EXACT_UNIT_MAP_COORDINATES[cleanCode]) return buildUnitCoordObj(cleanCode, EXACT_UNIT_MAP_COORDINATES[cleanCode]);
    if (EXACT_UNIT_MAP_COORDINATES[altCode]) return buildUnitCoordObj(cleanCode, EXACT_UNIT_MAP_COORDINATES[altCode]);

    // Loose match (strip non-alphanumeric to handle dash/space variations)
    var keyNoDash = cleanCode.replace(/[^A-Z0-9]/g, '');
    for (var k in EXACT_UNIT_MAP_COORDINATES) {
        if (k.replace(/[^A-Z0-9]/g, '') === keyNoDash) {
            return buildUnitCoordObj(k, EXACT_UNIT_MAP_COORDINATES[k]);
        }
    }

    return null; // Return null if unit position is not updated yet
}
